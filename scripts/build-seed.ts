/**
 * Builds supabase/seed.sql from data/edition-*.json.
 *
 *   npm run seed:build            write supabase/seed.sql
 *   npm run seed:check            fail if supabase/seed.sql is out of date
 *
 * The edition is validated first. score, grade and importance are not written:
 * the database computes them (see the stories_grade trigger).
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { validateEdition } from '../src/lib/validateEdition';
import type { Edition } from '../src/types/edition';

const root = join(__dirname, '..');
const out = join(root, 'supabase', 'seed.sql');

const MONTHS = ['jan', 'feb', 'mar', 'apr', 'may', 'jun', 'jul', 'aug', 'sep', 'oct', 'nov', 'dec'];
const ZONES: Record<string, string> = { BST: '+01:00', GMT: '+00:00', UTC: '+00:00' };

const pad = (n: number) => String(n).padStart(2, '0');

/** "Wednesday, 7 October 2026" or "7 Oct 2026" → "2026-10-07" */
export function isoDate(label: string): string {
  const m = /(\d{1,2}) ([A-Za-z]+) (\d{4})/.exec(label);
  const month = m ? MONTHS.indexOf(m[2].slice(0, 3).toLowerCase()) : -1;
  if (!m || month < 0) throw new Error(`Can't read a date from "${label}"`);
  return `${m[3]}-${pad(month + 1)}-${pad(Number(m[1]))}`;
}

/** "06:00 BST, 7 Oct 2026" → "2026-10-07T06:00:00+01:00" */
export function isoCompiled(label: string): string {
  const m = /^(\d{2}):(\d{2}) ([A-Z]{3}), (.+)$/.exec(label);
  if (!m || !(m[3] in ZONES)) throw new Error(`Can't read a compile time from "${label}"`);
  return `${isoDate(m[4])}T${m[1]}:${m[2]}:00${ZONES[m[3]]}`;
}

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;
const text = (s: string | null | undefined) => (s == null ? 'null' : lit(s));
const textArray = (xs: readonly string[]) =>
  xs.length === 0 ? `'{}'::text[]` : `array[${xs.map(lit).join(', ')}]::text[]`;
const jsonb = (v: unknown) => (v == null ? 'null' : `${lit(JSON.stringify(v))}::jsonb`);

export function buildSeed(edition: Edition, sourceFile: string): string {
  const { edition: meta, sections, outlets, stories } = edition;
  const editionId = `(select id from public.editions where issue = ${meta.issue})`;
  const lines: string[] = [];
  const push = (...xs: string[]) => lines.push(...xs);

  push(
    `-- Generated by scripts/build-seed.ts from ${sourceFile}. Do not edit by hand.`,
    `-- Re-running replaces issue ${meta.issue} (its stories and sources) and upserts sections and outlets.`,
    '',
    'begin;',
    '',
    'insert into public.sections (id, name, subs, sort) values',
    sections.map((s, i) => `  (${lit(s.id)}, ${lit(s.name)}, ${textArray(s.subs)}, ${i})`).join(',\n'),
    'on conflict (id) do update set name = excluded.name, subs = excluded.subs, sort = excluded.sort;',
    '',
    'insert into public.outlets (key, name, country) values',
    Object.entries(outlets)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([key, o]) => `  (${lit(key)}, ${lit(o.name)}, ${lit(o.country)})`)
      .join(',\n'),
    'on conflict (key) do update set name = excluded.name, country = excluded.country;',
    '',
    `delete from public.editions where issue = ${meta.issue};`,
    '',
    'insert into public.editions (issue, date, date_label, compiled_at, status) values',
    `  (${meta.issue}, ${lit(isoDate(meta.date))}, ${lit(meta.date)}, ${lit(isoCompiled(meta.compiled))}, 'published');`,
    '',
    'insert into public.stories (edition_id, slug, sort, sec, sub, head, say, stand, body, kept, cut, open,',
    '  primary_sources, m_corroboration, m_primary, m_stability, fig) values',
    stories
      .map((s, i) =>
        [
          `  (${editionId}, ${lit(s.id)}, ${i}, ${lit(s.sec)}, ${lit(s.sub)},`,
          `   ${lit(s.head)},`,
          `   ${text(s.say)},`,
          `   ${lit(s.stand)},`,
          `   ${textArray(s.body)},`,
          `   ${jsonb(s.kept)},`,
          `   ${jsonb(s.cut)},`,
          `   ${textArray(s.open)},`,
          `   ${textArray(s.primary)},`,
          `   ${s.m[0]}, ${s.m[1]}, ${s.m[2]}, ${jsonb(s.fig ?? null)})`,
        ].join('\n'),
      )
      .join(',\n') + ';',
    '',
    'insert into public.story_sources (story_id, sort, outlet_key, url, note)',
    'select s.id, v.sort, v.outlet_key, v.url, v.note',
    'from (values',
    stories
      .flatMap((s) =>
        s.src.map(
          (src, j) =>
            `  (${lit(s.id)}, ${j}, ${lit(src[0])}, ${lit(src[1])}, ${src.length === 3 ? lit(src[2]) : 'null::text'})`,
        ),
      )
      .join(',\n'),
    ') as v (slug, sort, outlet_key, url, note)',
    `join public.stories s on s.slug = v.slug and s.edition_id = ${editionId};`,
    '',
    'commit;',
    '',
  );
  return lines.join('\n');
}

function main() {
  const files = readdirSync(join(root, 'data'))
    .filter((f) => /^edition-\d{4}-\d{2}-\d{2}\.json$/.test(f))
    .sort();
  if (files.length === 0) throw new Error('No data/edition-*.json found');
  const file = files[files.length - 1];
  const edition: unknown = JSON.parse(readFileSync(join(root, 'data', file), 'utf8'));

  const { ok, errors } = validateEdition(edition);
  if (!ok) {
    console.error(`data/${file} is not a valid edition:\n  ${errors.join('\n  ')}`);
    process.exit(1);
  }
  const sql = buildSeed(edition as Edition, `data/${file}`);

  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(out, 'utf8');
    } catch {
      // missing counts as stale
    }
    if (current !== sql) {
      console.error('supabase/seed.sql is out of date. Run: npm run seed:build');
      process.exit(1);
    }
    console.log('supabase/seed.sql is up to date.');
    return;
  }
  writeFileSync(out, sql);
  console.log(`Wrote supabase/seed.sql from data/${file}`);
}

if (require.main === module) main();
